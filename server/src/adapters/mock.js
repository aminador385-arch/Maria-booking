export async function search({ vertical }) {
  const v = VERTICALS[vertical];
  if (!v) throw new Error('قطاع غير معروف: ' + vertical);
  const items = CATALOG[vertical] || [];
  return items.map((o, i) => ({
    id: `mock_${vertical}_${i}`,
    vertical,
    source: 'mock',
    title: o.t,
    subtitle: o.sub,
    tags: o.m,
    price: o.p,
    currency: 'USD',
    supplierRef: o.sup || null,
    bookable: true,
  }));
}

